export const translations = { en, ta, hi, ml, zh, ms } as const;
export type TKey = keyof typeof en;

type I18nCtx = { lang: Lang; setLang: (l: Lang) => void; t: (key: TKey, vars?: Record<string, string | number>) => string };
const Ctx = createContext<I18nCtx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try { const v = localStorage.getItem(STORAGE_KEY) as Lang | null; return v && v in translations ? v : "en"; } catch { return "en"; }
  });
  const setLang = (l: Lang) => { setLangState(l); try { localStorage.setItem(STORAGE_KEY, l); } catch {} };
  useEffect(() => { document.documentElement.lang = "en"; }, [lang]);
  const value = useMemo<I18nCtx>(() => ({
    lang, setLang,
    t: (key, vars) => {
      const dict = translations[lang] as Record<string, string>;
      let s = dict[key] ?? (translations.en as Record<string, string>)[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
      return s;
    },
  }), [lang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n requires I18nProvider");
  return v;
}

